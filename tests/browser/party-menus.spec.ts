import { selectLobbyGame } from "./select-lobby-game";
import { selectEntryCharacter } from "./select-entry-character";
import { test, expect } from "@playwright/test";

for (const reducedMotion of ["reduce", "no-preference"] as const) {
  test(`Partymenüs: Profil und lokales Setup (${reducedMotion})`, async ({ page }, info) => {
    await page.emulateMedia({ reducedMotion });
    await page.goto("/");
    await page.getByRole("button", { name: /^Gastprofil:/ }).click();
    await page.getByRole("textbox", { name: "Anzeigename" }).fill("Spieleabend");
    await page.screenshot({ path: info.outputPath("profil.png") });
    await page.getByRole("button", { name: "Speichern", exact: true }).click();
    await page.getByRole("button", { name: /Lokal spielen/ }).click();
    await expect(page.getByRole("navigation", {name: "Spiel auswählen"})).toBeVisible();
    await page.getByRole("button", { name: /^Durak / }).click();
    await expect(page.getByRole("button", {name:"Durak starten",exact:true})).toBeDisabled();
    await selectEntryCharacter(page, "Prime Rick", "Figur von Spieler 1");
    await selectEntryCharacter(page, "Korvo", "Figur von Spieler 2");
    await page.getByRole("checkbox", { name: /Schummelmodus/ }).check();
    await expect(page.getByRole("button", { name: "Durak starten", exact: true })).toBeEnabled();
    await page.getByLabel("Name von Spieler 1").fill("Anna");
    await page.getByLabel("Name von Spieler 2").fill("Ben");
    await page.getByRole("button",{name:"Spieler hinzufügen"}).click();
    await expect(page.getByRole("button",{name:"Durak starten"})).toBeDisabled();
    await page.getByRole("button",{name:"Spieler entfernen"}).click();
    await expect(page.locator("summary").filter({hasText:"Figur von Spieler 2"})).toContainText("Korvo");
    await page.locator("summary").filter({hasText:"Figur von Spieler 1"}).click();
    const gallery = page.getByRole("group",{name:"Figur von Spieler 1",exact:true});
    await expect(gallery.getByRole("button",{name:"Prime Rick",exact:true})).toHaveAttribute("aria-pressed","true");
    await expect(page.getByRole("img",{name:"3D-Vorschau: Prime Rick"})).toHaveAttribute("data-webgl","ready");
    await expect(gallery.getByRole("button")).toHaveCount(24);
    await gallery.getByRole("button").first().evaluate(el => el.scrollIntoView({block:"start"}));
    await page.screenshot({path:info.outputPath("lokale-portraetkarten.png")});
    await gallery.getByRole("button",{name:"Prime Rick",exact:true}).click();
    await page.evaluate(()=>window.scrollTo(0,0));
    const portrait = await page.locator(".local-player-setup summary .character-avatar").first().boundingBox();
    expect(portrait!.width / portrait!.height).toBeGreaterThan(.8);
    expect(portrait!.width / portrait!.height).toBeLessThan(1.2);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath("lokales-setup.png"), fullPage: true });
    await page.setViewportSize({ width: 320, height: 640 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.getByRole("button", { name: "Durak starten", exact: true }).click();
    const skip = page.getByRole("button", { name: "Intro überspringen" });
    if (reducedMotion === "no-preference") await skip.click();
    await expect(page.getByRole("button", { name: "Karten anzeigen", exact: true })).toBeVisible();
  });
}

test("Partymenüs: Online-Auswahl, Lobby und Figurenwechsel", async ({ page }, info) => {
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/");
  await page.getByRole("button", { name: /Online spielen/ }).click();
  await page.getByRole("button", { name: /^Raum erstellen/ }).click();
  await expect(page.getByRole("button", { name: "Neuen Raum erstellen", exact: true })).toBeDisabled();
  await selectEntryCharacter(page, "Morty Smith");
  await expect(page.locator("summary .character-avatar img")).toBeVisible();
  await page.screenshot({ path: info.outputPath("online-auswahl.png"), fullPage: true });
  await page.getByRole("button", { name: "Neuen Raum erstellen", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Lobby", exact: true })).toBeVisible();
  await selectLobbyGame(page, "party");
  await expect(page.getByRole("combobox",{name:"Runden",exact:true})).toBeVisible();
  await expect(page.getByRole("combobox", { name: "Tempo", exact: true })).toHaveCount(0);
  await expect(page.getByText("Minispiele ausprobieren",{exact:true})).toHaveCount(0);
  await selectEntryCharacter(page, "Prime Rick");
  await expect(page.locator(".player-row").first()).toContainText("Prime Rick");
  await expect(page.locator(".room details[open]")).toHaveCount(0);
  await page.locator(".room summary").filter({hasText:"Spiel auswählen"}).click();
  await page.screenshot({ path: info.outputPath("spielgalerie.png") });
  await page.locator(".room summary").filter({hasText:"Deine Spielfigur"}).click();
  await page.locator(".room details[open] summary").evaluate(el => el.scrollIntoView({block:"start"}));
  await page.screenshot({ path: info.outputPath("figurengalerie.png") });
  await page.locator(".room summary").filter({hasText:"Deine Spielfigur"}).click();
  await page.screenshot({ path: info.outputPath("lobby-handy.png") });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("lobby.png"), fullPage: true });
  await page.setViewportSize({ width: 320, height: 640 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("lobby-320.png"), fullPage: true });
});

test("Partymenüs: Handy-Einladung mit lesbarem QR und Textcode", async ({ page }, info) => {
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/");
  await page.getByRole("button", { name: /Online spielen/ }).click();
  await page.getByRole("button", { name: /^Raum erstellen/ }).click();
  await selectEntryCharacter(page, "Morty Smith");
  await page.getByRole("radio", { name: /Dieses Handy/ }).check();
  await page.getByRole("button", { name: "Neuen Raum erstellen", exact: true }).click();
  await page.getByRole("button", { name: "Gerät verbinden", exact: true }).click();
  const dialog = page.locator(".pair-dialog");
  await expect(dialog).toBeVisible();
  await expect(dialog.locator(".pair-qr")).toBeVisible();
  await dialog.getByText("Textcode anzeigen", { exact: true }).click();
  await expect(dialog.getByRole("textbox", { name: "Eigener Verbindungscode" })).toHaveValue(/^GSG1\./);
  const bounds = await dialog.locator(".pair-qr").boundingBox();
  expect(Math.abs(bounds!.width - bounds!.height)).toBeLessThan(1);
  await page.screenshot({ path: info.outputPath("qr-einladung.png") });
  await dialog.getByRole("button", { name: "Schließen", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("heading", { name: "Lobby", exact: true })).toBeVisible();
});
